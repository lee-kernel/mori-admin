CREATE TABLE IF NOT EXISTS "user_group" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id >= 0),
    name VARCHAR(64) NOT NULL UNIQUE,
    description VARCHAR(255) NULL,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "user" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id >= 0),
    username VARCHAR(64) NOT NULL UNIQUE,
    display_name VARCHAR(128) NOT NULL,
    email VARCHAR(255) NULL UNIQUE,
    hashed_password VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_count INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
    login_locked_until TIMESTAMPTZ NULL DEFAULT NULL,
    token_version INTEGER NOT NULL DEFAULT 0 CHECK (token_version >= 0),
    group_id BIGINT NULL REFERENCES user_group(id) ON DELETE RESTRICT,
    last_login_at TIMESTAMPTZ NULL DEFAULT NULL,
    last_login_ip VARCHAR(45) NULL DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "menu" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id >= 0),
    parent_id BIGINT NULL REFERENCES menu(id) ON DELETE RESTRICT,
    name VARCHAR(64) NOT NULL,
    path VARCHAR(128) NOT NULL UNIQUE,
    permission_key VARCHAR(128) NOT NULL UNIQUE,
    component VARCHAR(128) NULL,
    icon VARCHAR(64) NULL,
    redirect VARCHAR(128) NULL,
    sort INT NOT NULL DEFAULT 0,
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    is_external BOOLEAN NOT NULL DEFAULT FALSE,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "role_menu" (
    role_id BIGINT NOT NULL CHECK (role_id >= 0),
    menu_id BIGINT NOT NULL CHECK (menu_id >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, menu_id),
    CONSTRAINT fk_role_menu_role FOREIGN KEY (role_id) REFERENCES "user_group" (id) ON DELETE CASCADE,
    CONSTRAINT fk_role_menu_menu FOREIGN KEY (menu_id) REFERENCES "menu" (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS operation_permission (
    key VARCHAR(128) PRIMARY KEY,
    label VARCHAR(128) NOT NULL,
    domain VARCHAR(64) NOT NULL,
    operation VARCHAR(32) NOT NULL,
    high_risk BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS role_permission (
    role_id BIGINT NOT NULL REFERENCES user_group(id) ON DELETE CASCADE,
    permission_key VARCHAR(128) NOT NULL REFERENCES operation_permission(key),
    PRIMARY KEY (role_id, permission_key)
);

CREATE TABLE IF NOT EXISTS "login_log" (
    trace_id VARCHAR(32) NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id >= 0),
    user_id BIGINT NULL CHECK (user_id >= 0),
    username VARCHAR(64) NULL,
    ip_address VARCHAR(45) NULL,
    platform VARCHAR(128) NULL,
    browser VARCHAR(128) NULL,
    event_type SMALLINT NOT NULL DEFAULT 1,
    login_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "operation_log" (
    trace_id VARCHAR(32) NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id >= 0),
    user_id BIGINT NULL CHECK (user_id >= 0),
    username VARCHAR(64) NULL,
    method VARCHAR(16) NOT NULL,
    url VARCHAR(512) NOT NULL,
    title VARCHAR(255) NULL,
    status_code INT NOT NULL DEFAULT 0,
    duration_ms INT NOT NULL DEFAULT 0,
    operated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

