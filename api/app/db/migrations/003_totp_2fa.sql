CREATE TABLE IF NOT EXISTS user_totp (
    user_id BIGINT PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
    secret_encrypted TEXT NULL,
    pending_secret_encrypted TEXT NULL,
    pending_expires_at TIMESTAMPTZ NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    last_used_step BIGINT NULL,
    enabled_at TIMESTAMPTZ NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_totp_recovery_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id >= 0),
    user_id BIGINT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    code_hash VARCHAR(255) NOT NULL,
    used_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_user_totp_recovery_code_user_id
    ON user_totp_recovery_code (user_id);

CREATE TRIGGER trg_user_totp_updated_at
BEFORE UPDATE ON user_totp
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

UPDATE mori_admin_schema_version SET version = 3;
